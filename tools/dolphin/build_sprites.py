#!/usr/bin/env python3
"""Build the Dolphin Lab sprites from their text art.

    tools/dolphin/build_sprites.py            write helpers/rg_sprites.{c,h}
    tools/dolphin/build_sprites.py --check    fail if those files are stale
    tools/dolphin/build_sprites.py --preview DIR
                                              also write DIR/sprites.png

The art lives in art/dolphin/*.txt (read in name order): "sprite NAME", then
one row per line with '#' for a black pixel and '.' for a transparent one; a
blank line ends a sprite and '#' at the start of any other line is a comment
only outside a sprite. Every row of a sprite has the same width.

The output is XBM data (rows of whole bytes, least significant bit leftmost),
the format canvas_draw_xbm() takes, packed into one array with a table of
sizes and offsets. Pure C with no SDK header, so the host tests use it too.
Standard library only.
"""
import argparse
import os
import re
import struct
import sys
import zlib

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ART = os.path.join(ROOT, "art", "dolphin")
OUT_C = os.path.join(ROOT, "helpers", "rg_sprites.c")
OUT_H = os.path.join(ROOT, "helpers", "rg_sprites.h")
MAX_SIDE = 64


def parse(path):
    sprites = []
    current = None
    for lineno, raw in enumerate(open(path, encoding="utf-8"), 1):
        line = raw.rstrip("\n")
        where = "%s:%d" % (os.path.relpath(path, ROOT), lineno)
        if current is not None:
            if not line.strip():
                current = None
                continue
            if set(line) - set(".#"):
                raise SystemExit("%s: only '.' and '#' in a sprite row" % where)
            if current["rows"] and len(line) != len(current["rows"][0]):
                raise SystemExit("%s: row width %d, expected %d" % (where, len(line), len(current["rows"][0])))
            current["rows"].append(line)
            continue
        if line.startswith("sprite "):
            name = line.split()[1]
            if not re.fullmatch(r"[a-z][a-z0-9_]*", name):
                raise SystemExit("%s: bad sprite name %r" % (where, name))
            current = {"name": name, "rows": [], "where": where}
            sprites.append(current)
        elif line.strip() and not line.startswith("#"):
            raise SystemExit("%s: expected 'sprite NAME', a comment or a blank line" % where)
    return sprites


def load():
    sprites = []
    for name in sorted(os.listdir(ART)):
        if name.endswith(".txt"):
            sprites += parse(os.path.join(ART, name))
    seen = set()
    for s in sprites:
        if s["name"] in seen:
            raise SystemExit("%s: sprite %s defined twice" % (s["where"], s["name"]))
        seen.add(s["name"])
        h, w = len(s["rows"]), len(s["rows"][0]) if s["rows"] else 0
        if not (1 <= w <= MAX_SIDE and 1 <= h <= MAX_SIDE):
            raise SystemExit("%s: %s is %dx%d (1..%d)" % (s["where"], s["name"], w, h, MAX_SIDE))
        if "#" not in "".join(s["rows"]):
            raise SystemExit("%s: %s is empty" % (s["where"], s["name"]))
    return sprites


def xbm(rows):
    out = []
    for row in rows:
        for x0 in range(0, len(row), 8):
            b = 0
            for k, ch in enumerate(row[x0 : x0 + 8]):
                if ch == "#":
                    b |= 1 << k
            out.append(b)
    return out


def enum_name(name):
    return "RgSprite" + "".join(p.capitalize() for p in name.split("_"))


def generate(sprites):
    data = []
    table = []
    for s in sprites:
        bits = xbm(s["rows"])
        table.append((s["name"], len(s["rows"][0]), len(s["rows"]), len(data)))
        data += bits
    names = ", ".join(s["name"] for s in sprites)
    header = [
        "/* Generated by tools/dolphin/build_sprites.py from the text art in art/dolphin: do not edit. */",
        "/**",
        " * @file rg_sprites.h",
        " * @brief Dolphin Lab sprites: the mascot, its props and the menu icons.",
        " *",
        " * XBM bitmaps (rows of whole bytes, least significant bit leftmost), as",
        " * canvas_draw_xbm() takes them. Pure data, no SDK header.",
        " */",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        "typedef enum {",
    ]
    header += ["    %s," % enum_name(n) for n, _, _, _ in table]
    header += [
        "    RgSpriteCount,",
        "} RgSpriteId;",
        "",
        "typedef struct {",
        "    uint8_t w;",
        "    uint8_t h;",
        "    uint16_t offset; // into rg_sprite_bits",
        "} RgSprite;",
        "",
        "extern const RgSprite rg_sprites[RgSpriteCount];",
        "extern const uint8_t rg_sprite_bits[];",
        "",
        "/* Bytes of sprite data in all. */",
        "#define RG_SPRITE_BYTES %du" % len(data),
        "",
    ]
    src = [
        "/* Generated by tools/dolphin/build_sprites.py from the text art in art/dolphin: do not edit. */",
        "/* Sprites: %s. */" % names,
        '#include "rg_sprites.h"',
        '#include "../radiogeddon_edition.h"',
        "",
        "#if RG_FEATURE_DOLPHIN_LAB",
        "",
        "// clang-format off",
        "const RgSprite rg_sprites[RgSpriteCount] = {",
    ]
    src += ["    [%s] = {%d, %d, %d}," % (enum_name(n), w, h, off) for n, w, h, off in table]
    src += ["};", "", "const uint8_t rg_sprite_bits[%d] = {" % len(data)]
    for i in range(0, len(data), 12):
        src.append("    " + " ".join("0x%02x," % b for b in data[i : i + 12]))
    src += ["};", "// clang-format on", "", "#endif", ""]
    return "\n".join(header), "\n".join(src)


def write_png(path, sprites, scale=4):
    gap = 2
    w = sum(len(s["rows"][0]) + gap for s in sprites) + gap
    h = max(len(s["rows"]) for s in sprites) + 2 * gap
    px = [[(255, 140, 0)] * w for _ in range(h)]
    x0 = gap
    for s in sprites:
        for y, row in enumerate(s["rows"]):
            for x, ch in enumerate(row):
                if ch == "#":
                    px[gap + y][x0 + x] = (0, 0, 0)
        x0 += len(s["rows"][0]) + gap
    rows = []
    for line in px:
        big = []
        for c in line:
            big += [c] * scale
        rows += [big] * scale
    raw = b"".join(b"\0" + bytes(v for c in r for v in c) for r in rows)

    def chunk(tag, body):
        return struct.pack(">I", len(body)) + tag + body + struct.pack(">I", zlib.crc32(tag + body))

    with open(path, "wb") as f:
        f.write(b"\x89PNG\r\n\x1a\n")
        f.write(chunk(b"IHDR", struct.pack(">IIBBBBB", w * scale, h * scale, 8, 2, 0, 0, 0)))
        f.write(chunk(b"IDAT", zlib.compress(raw, 9)))
        f.write(chunk(b"IEND", b""))


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="fail if the generated files are stale")
    ap.add_argument("--preview", metavar="DIR", help="also write DIR/sprites.png")
    args = ap.parse_args()
    sprites = load()
    header, source = generate(sprites)
    if args.preview:
        os.makedirs(args.preview, exist_ok=True)
        write_png(os.path.join(args.preview, "sprites.png"), sprites)
    if args.check:
        stale = []
        for path, text in ((OUT_H, header), (OUT_C, source)):
            if not os.path.exists(path) or open(path, encoding="utf-8").read() != text:
                stale.append(os.path.relpath(path, ROOT))
        if stale:
            print("stale: %s (run tools/dolphin/build_sprites.py)" % ", ".join(stale))
            return 1
        print("sprites up to date: %d sprites, %d bytes" % (len(sprites), sum(len(xbm(s["rows"])) for s in sprites)))
        return 0
    for path, text in ((OUT_H, header), (OUT_C, source)):
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
    print("wrote %d sprites (%d bytes)" % (len(sprites), sum(len(xbm(s["rows"])) for s in sprites)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
