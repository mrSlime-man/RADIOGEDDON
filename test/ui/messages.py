#!/usr/bin/env python3
"""List every message RadioGeddon shows, for the UI tests' card check.

    messages.py OUT.inc FILE.c [FILE.c ...]

Finds the literal (header, text) pairs passed to
radiogeddon_scene_show_message() and assigned as a module refusal
(radiogeddon_module_error), and writes them as C initialisers
{"header", "text"}, so test_ui_lab draws each one on a card. Messages built
at run time are covered by the tests' own long examples.
Standard library only.
"""
import re
import sys

LIT = r'"(?:[^"\\]|\\.)*"'
CALL = re.compile(
    r"radiogeddon_scene_show_message\(\s*app\s*,\s*((?:%s\s*)+),\s*((?:%s\s*)+)\)" % (LIT, LIT), re.S
)
PAIR = re.compile(r"\*header\s*=\s*(%s);\s*\*text\s*=\s*((?:%s\s*)+);" % (LIT, LIT), re.S)


def join(lits):
    return '"%s"' % "".join(re.findall(r'"((?:[^"\\]|\\.)*)"', lits))


def main(argv):
    out = []
    for path in argv[2:]:
        src = open(path, encoding="utf-8").read()
        for rx in (CALL, PAIR):
            for m in rx.finditer(src):
                item = "{%s, %s}," % (join(m.group(1)), join(m.group(2)))
                if item not in out:
                    out.append(item)
    if len(out) < 10:
        raise SystemExit("only %d messages found: the patterns no longer match" % len(out))
    with open(argv[1], "w", encoding="utf-8") as f:
        f.write("/* Generated by test/ui/messages.py. */\n" + "\n".join(out) + "\n")
    print("%d messages" % len(out))


if __name__ == "__main__":
    main(sys.argv)
